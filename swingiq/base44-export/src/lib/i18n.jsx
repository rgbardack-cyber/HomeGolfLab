// Fill missing keys from 'en' as fallback for it, ja, zh
const ALL_LANGS = ['it', 'ja', 'zh'];
ALL_LANGS.forEach(lang => {
  if (!T[lang]) T[lang] = {};
  Object.keys(T.en).forEach(key => {
    if (!T[lang][key]) T[lang][key] = T.en[key];
  });
});

// Also fill any missing keys for defined languages
Object.keys(T).forEach(lang => {
  if (lang !== 'en') {
    Object.keys(T.en).forEach(key => {
      if (!T[lang][key]) T[lang][key] = T.en[key];
    });
  }
});

export const LangContext = createContext(null);

export function LangProvider({ children }) {
  const stored = typeof localStorage !== 'undefined' ? localStorage.getItem('golf_lang') : 'es';
  const [lang, setLangState] = useState(stored || 'es');

  const setLang = (code) => {
    setLangState(code);
    localStorage.setItem('golf_lang', code);
  };

  const t = (key) => T[lang]?.[key] || T.en?.[key] || key;

  return <LangContext.Provider value={{ lang, setLang, t }}>{children}</LangContext.Provider>;
}

export const useLang = () => useContext(LangContext);